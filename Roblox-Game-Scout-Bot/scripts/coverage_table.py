"""Regenerate the coverage-per-module table in ARCHITECTURE.md from coverage.xml.

CI (`.github/workflows/ci.yml`) and the documented local command both emit
`coverage.xml` next to this script's directory. `coverage_table.py` reads
that XML, keeps the bot's production modules only (tests/, scripts/ and
test scaffolding are excluded — they measure the suite, not the bot), and
rewrites the marker block in ARCHITECTURE.md so the weakest-tested files
stand out: rows are sorted ascending by coverage and anything below
COVERAGE_WARN is starred.

Usage:
    py -m pytest tests/ -q -p no:warnings --cov=. --cov-report=xml
    py scripts/coverage_table.py            # rewrite the ARCHITECTURE.md table
    py scripts/coverage_table.py --check    # exit 1 if the table is stale

`--check` is stable for a committed coverage.xml + table pair (the same
input renders the same output, so a PR that changes tested code without
refreshing the table is caught); it is deliberately NOT wired into the
CI test job, which produces a fresh coverage.xml every run and should
not need a doc commit to stay green.
"""

import argparse
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent  # Roblox-Game-Scout-Bot/

START_MARKER = "<!-- coverage-table:start (generated by scripts/coverage_table.py -- do not edit this block) -->"
END_MARKER = "<!-- coverage-table:end -->"

# Files below this line-coverage percentage get the alert star in the table.
COVERAGE_WARN = 50.0

# Directories whose .py files measure the suite or are build output, not the bot.
EXCLUDED_DIRS = {"tests", "scripts", "__pycache__", "htmlcov"}


def _class_rows(xml_path: Path) -> dict[str, tuple[int, int, float]]:
    """{filename: (statements, missing, coverage_pct)} from coverage.py XML."""
    root = ET.parse(xml_path).getroot()
    rows: dict[str, tuple[int, int, float]] = {}
    for cls in root.iter("class"):
        filename = (cls.get("filename") or "").replace("\\", "/")
        if not filename:
            continue
        summary = cls.find("summary")
        if summary is not None:
            statements = int(summary.get("statements", "0"))
            missing = int(summary.get("missing", "0"))
        else:  # pre-7.x schema that counts <line> elements directly
            lines_el = cls.find("lines")
            line_entries = list(lines_el) if lines_el is not None else []
            statements = len(line_entries)
            missing = sum(1 for ln in line_entries if ln.get("hits") == "0")
        rate = 100.0 * (statements - missing) / statements if statements else 0.0
        # one file can contribute several <class> blocks; aggregate them
        if filename in rows:
            stmts, miss, _ = rows[filename]
            statements += stmts
            missing += miss
            rate = 100.0 * (statements - missing) / statements if statements else 0.0
        rows[filename] = (statements, missing, rate)
    return rows


def build_table(xml_path: Path) -> str:
    """Render the full block (heading omitted) that lives between the markers."""
    rows = []
    for filename, (statements, missing, rate) in _class_rows(xml_path).items():
        parts = Path(filename).parts
        if not filename.endswith(".py") or not parts:
            continue
        if parts[0] in EXCLUDED_DIRS or parts[0] == ".":
            continue
        if any(part.startswith("test_") or part == "conftest.py" for part in parts):
            continue
        if len(parts) > 1:  # only bot-root modules make the table
            continue
        rows.append((parts[-1], statements, missing, rate))

    if not rows:
        raise SystemExit(f"no production modules found in {xml_path}")

    rows.sort(key=lambda r: (r[3], r[0]))  # weakest first, name as tie-break
    lines = [
        "### Coverage health (generated — rerun `py scripts/coverage_table.py` after `--cov-report=xml`)",
        "",
        "Bot modules only (`tests/` and `scripts/` excluded), weakest first.",
        "⚠️ marks files below 50% line coverage. Source: CI's `coverage.xml` "
        "(`py -m pytest tests/ --cov=. --cov-report=xml`).",
        "",
        "| Module | Stmts | Miss | Cover |",
        "|---|---:|---:|---:|",
    ]
    for name, statements, missing, rate in rows:
        star = " ⚠️" if rate < COVERAGE_WARN else ""
        lines.append(f"| {name}{star} | {statements} | {missing} | {rate:.0f}% |")
    return "\n".join(lines)


def _marker_bounds(text: str):
    """(start, end) slice indices of the committed marker block, or None."""
    try:
        start = text.index(START_MARKER)
        end = text.index(END_MARKER, start)
    except ValueError:
        return None
    return start, end + len(END_MARKER)


def upsert_architecture(xml_path: Path, md_path: Path) -> bool:
    """Replace (or create) the marker block. Returns True when changed."""
    block = build_table(xml_path)
    text = md_path.read_text(encoding="utf-8")
    bounds = _marker_bounds(text)
    if bounds is None:
        md_path.write_text(
            text.rstrip() + f"\n\n{START_MARKER}\n{block}\n{END_MARKER}\n",
            encoding="utf-8",
        )
        return True

    start, end = bounds
    replacement = f"{START_MARKER}\n{block}\n{END_MARKER}"
    updated = text[:start] + replacement + text[end:]
    if updated == text:
        return False
    md_path.write_text(updated, encoding="utf-8")
    return True


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--xml", type=Path, default=HERE / "coverage.xml")
    parser.add_argument("--md", type=Path, default=HERE / "ARCHITECTURE.md")
    parser.add_argument("--check", action="store_true",
                        help="exit 1 if the committed table is stale (no write)")
    args = parser.parse_args(argv)

    if not args.xml.exists():
        print(f"coverage.xml not found at {args.xml} — run "
              "`py -m pytest tests/ --cov=. --cov-report=xml` first", file=sys.stderr)
        return 2

    if args.check:
        fresh = build_table(args.xml)
        text = args.md.read_text(encoding="utf-8")
        bounds = _marker_bounds(text)
        if bounds is None:
            print(f"{args.md} has no coverage table yet", file=sys.stderr)
            return 1
        start, end = bounds
        current = text[start + len(START_MARKER):end - len(END_MARKER)].strip()
        if current != fresh:
            print("coverage table in ARCHITECTURE.md is stale — run "
                  "`py scripts/coverage_table.py` and commit the result",
                  file=sys.stderr)
            return 1
        print("coverage table is up to date")
        return 0

    changed = upsert_architecture(args.xml, args.md)
    print(f"{args.md} " + ("updated" if changed else "already up to date"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
